    def install_pet_charset(self, memory: C64Memory, target_addr: int = 0x3800) -> None:
        """
        Installs PET custom graphics onto the simulated C64 Memory at target_addr.
        1. Copies standard dummy font/charset data to target_addr
        2. Overrides offsets $300-$3FF (characters $60-$7F) with PET_GRAPHICS_DATA
        3. Configures standard VIC_MEM for the target_addr.
        """
        # Overwrite target address offsets
        offset_base = target_addr + 0x0300
        for i, val in enumerate(self.PET_GRAPHICS_DATA):
            memory.write(offset_base + i, val)

        # Update VIC location config
        vic = VICII(memory)
        vic.set_charset_location(target_addr)
